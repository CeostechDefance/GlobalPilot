#!/usr/bin/env python3
"""Puts the wildfire model on the terrain at a coordinate, for one world and aircraft.

    python3 place_wildfire.py 36.9759 30.6779

Writes scenarios/<region>_<model>.sdf, which px4-rc.gzsim spawns together with the aircraft.
The ground height comes from the same terrain tiles the simulator draws.
"""
import argparse
import gzip
import json
import math
import os
import struct

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REGIONS = os.path.join(HERE, '..', 'gz_geo_terrain', 'regions')
LEVEL = 13
TILE_DEG = 180.0 / 2 ** LEVEL
WGS84_A, WGS84_E2 = 6378137.0, 6.69437999014e-3


def zigzag_delta(values):
    values = values.astype(np.int64)
    return np.cumsum((values >> 1) ^ -(values & 1))


def ground_height(data_root, region, lat, lon):
    """Mean height of the terrain vertices within 45 m of the point (the grid spacing is about 30 m)."""
    x, y = int((lon + 180) / TILE_DEG), int((lat + 90) / TILE_DEG)
    path = os.path.join(data_root, region, 'terrain', str(LEVEL), str(x), f'{y}.terrain')
    with open(path, 'rb') as f:
        raw = f.read()
    if raw[:2] == b'\x1f\x8b':
        raw = gzip.decompress(raw)
    h_min, h_max = struct.unpack_from('<ff', raw, 24)
    count = struct.unpack_from('<I', raw, 88)[0]
    u, v, h = np.frombuffer(raw, '<u2', count=3 * count, offset=92).reshape(3, count)
    lons = x * TILE_DEG - 180 + zigzag_delta(u) / 32767 * TILE_DEG
    lats = y * TILE_DEG - 90 + zigzag_delta(v) / 32767 * TILE_DEG
    heights = h_min + zigzag_delta(h) / 32767 * (h_max - h_min)
    east = (lons - lon) * 111320 * math.cos(math.radians(lat))
    north = (lats - lat) * 111320
    near = np.hypot(east, north) < 45
    if not near.any():
        raise SystemExit(f'no terrain vertices near {lat} {lon}')
    return float(heights[near].mean())


def ecef(lat, lon, h):
    phi, lam = math.radians(lat), math.radians(lon)
    n = WGS84_A / math.sqrt(1 - WGS84_E2 * math.sin(phi) ** 2)
    return np.array([(n + h) * math.cos(phi) * math.cos(lam),
                     (n + h) * math.cos(phi) * math.sin(lam),
                     (n * (1 - WGS84_E2) + h) * math.sin(phi)])


def world_position(origin, point):
    """East, north, up of a point from the world origin, including Earth curvature as the terrain does."""
    phi, lam = math.radians(origin[0]), math.radians(origin[1])
    d = ecef(*point) - ecef(*origin)
    east = -math.sin(lam) * d[0] + math.cos(lam) * d[1]
    north = -math.sin(phi) * math.cos(lam) * d[0] - math.sin(phi) * math.sin(lam) * d[1] + math.cos(phi) * d[2]
    up = math.cos(phi) * math.cos(lam) * d[0] + math.cos(phi) * math.sin(lam) * d[1] + math.sin(phi) * d[2]
    return east, north, up


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('lat', type=float)
    ap.add_argument('lon', type=float)
    ap.add_argument('--region', default='antalya')
    ap.add_argument('--aircraft', default='gasi_ffa')
    args = ap.parse_args()

    with open(os.path.join(REGIONS, f'{args.region}.json')) as f:
        origin = json.load(f)['origin']
    data_root = os.environ.get('GEO_TERRAIN_DATA', os.path.expanduser('~/.local/share/gz-geo-terrain'))
    origin_h = ground_height(data_root, args.region, origin['lat'], origin['lon'])
    site_h = ground_height(data_root, args.region, args.lat, args.lon)
    east, north, up = world_position((origin['lat'], origin['lon'], origin_h), (args.lat, args.lon, site_h))

    out_dir = os.path.join(HERE, 'scenarios')
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, f'{args.region}_{args.aircraft}.sdf')
    with open(path, 'w') as f:
        f.write(f"""<?xml version="1.0"?>
<!-- Generated by place_wildfire.py {args.lat} {args.lon}: ground height {site_h:.1f} m AMSL. -->
<sdf version="1.9">
  <include>
    <uri>model://wildfire</uri>
    <pose>{east:.1f} {north:.1f} {up:.1f} 0 0 0</pose>
  </include>
</sdf>
""")
    print(f'{path}\nworld position east {east:.1f} north {north:.1f} up {up:.1f} m, ground {site_h:.1f} m AMSL')


if __name__ == '__main__':
    main()
