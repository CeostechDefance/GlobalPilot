#!/usr/bin/env python3
"""Generates wildfire_heat: hidden hot geometry that makes the wildfire visible to a thermal camera.

Gazebo thermal cameras do not render particles, so the wildfire model has no thermal image. These boxes have
temperatures and full transparency: fire_camera does not see them and the thermal camera does. A ground test showed
this for a plain box, while a transparent OBJ mesh rendered as opaque white, so do not merge the boxes into a mesh.

Spawn it at the same pose as model://wildfire. The layout is a fixed pseudo-random one, not a fire simulation.
"""
import os
import random

MODEL_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'wildfire_heat')
FIRE_HALF_SIZE_M = 30.0  # the flames emitter covers 60 x 60 m
BOX_BOTTOM_M = -3.0  # keeps boxes in contact with sloping ground
CLUSTERS = 6
SEED = 7

# name, kelvin, box count, smallest and largest box width in metres, spread around a cluster in metres
BANDS = (
    ('core', 900.0, 15, 1.5, 3.0, 4.0),
    ('flame', 650.0, 35, 1.0, 2.5, 7.0),
    ('ember', 450.0, 70, 0.7, 2.0, 12.0),
)


def box_visual(name, kelvin, x, y, width, top):
    height = top - BOX_BOTTOM_M
    z = (top + BOX_BOTTOM_M) / 2
    return f'''      <visual name="{name}">
        <pose>{x:.2f} {y:.2f} {z:.2f} 0 0 0</pose>
        <cast_shadows>false</cast_shadows>
        <transparency>1</transparency>
        <geometry><box><size>{width:.2f} {width:.2f} {height:.2f}</size></box></geometry>
        <material><diffuse>1 0 0 1</diffuse></material>
        <plugin filename="gz-sim-thermal-system" name="gz::sim::systems::Thermal">
          <temperature>{kelvin}</temperature>
        </plugin>
      </visual>
'''


def band_visuals(rng, centers, name, kelvin, count, min_width, max_width, spread):
    visuals = []
    for index in range(count):
        cx, cy = rng.choice(centers)
        x = max(-FIRE_HALF_SIZE_M, min(FIRE_HALF_SIZE_M, rng.gauss(cx, spread)))
        y = max(-FIRE_HALF_SIZE_M, min(FIRE_HALF_SIZE_M, rng.gauss(cy, spread)))
        visuals.append(box_visual(f'{name}_{index}', kelvin, x, y, rng.uniform(min_width, max_width),
                                  rng.uniform(0.5, 4.0)))
    return visuals


def main():
    rng = random.Random(SEED)
    limit = FIRE_HALF_SIZE_M - 8
    centers = [(rng.uniform(-limit, limit), rng.uniform(-limit, limit)) for _ in range(CLUSTERS)]
    visuals = []
    for band in BANDS:
        visuals += band_visuals(rng, centers, *band)

    os.makedirs(MODEL_DIR, exist_ok=True)
    with open(os.path.join(MODEL_DIR, 'model.sdf'), 'w') as handle:
        handle.write(f'''<?xml version="1.0"?>
<!-- Generated by generate_wildfire_heat.py. Spawn at the same pose as model://wildfire. -->
<sdf version="1.9">
  <model name="wildfire_heat">
    <static>true</static>
    <link name="heat_link">
{''.join(visuals)}    </link>
  </model>
</sdf>
''')
    with open(os.path.join(MODEL_DIR, 'model.config'), 'w') as handle:
        handle.write('''<?xml version="1.0"?>
<model>
  <name>wildfire_heat</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <author><name>Ceostech</name></author>
  <description>Transparent hot boxes that give model://wildfire a thermal camera image.</description>
</model>
''')


if __name__ == '__main__':
    main()
